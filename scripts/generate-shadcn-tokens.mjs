import { readFile, writeFile } from 'node:fs/promises';
import { getCohesionShadcnTheme } from '../theme/create-shadcn-theme.mjs';

const unknown = process.argv.slice(2).filter(argument => argument !== '--check');
if (unknown.length) throw new Error(`Unknown argument: ${unknown.join(', ')}`);
const source = getCohesionShadcnTheme();
const snapshot = new URL('../theme/shadcn-tokens.json', import.meta.url);
const json = `${JSON.stringify(source, null, 2)}\n`;
const targets = {
  light: '.shadcn-scope, .shadcn-scope[data-shadcn-theme="light"]',
  dark: '.shadcn-scope[data-shadcn-theme="dark"]',
};
const css = [
  '/* Generated by theme/create-shadcn-theme.mjs from the official preset and shared COHESION brand; do not edit. */',
  ...Object.entries(targets).map(([mode, selector]) => `${selector} {\n${Object.entries(source[mode]).map(([key, value]) => `  --${key}: ${value};`).join('\n')}\n  color-scheme: ${mode};\n}`),
  '',
].join('\n');
const output = new URL('../preview/shadcn/tokens.css', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(snapshot, 'utf8').catch(() => '') !== json) throw new Error('theme/shadcn-tokens.json is stale. Run node scripts/generate-shadcn-tokens.mjs.');
  if (await readFile(output, 'utf8').catch(() => '') !== css) throw new Error('preview/shadcn/tokens.css is stale. Run node scripts/generate-shadcn-tokens.mjs.');
  console.log('shadcn JSON and scoped CSS match the shared COHESION brand theme.');
} else {
  await writeFile(snapshot, json);
  await writeFile(output, css);
  console.log('Generated theme/shadcn-tokens.json and preview/shadcn/tokens.css.');
}
